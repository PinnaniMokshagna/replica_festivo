export function getVendorImageAndGallery(vendor: Vendor): { image: string; gallery: string[] } {
  const categoryDefault = CATEGORY_DEFAULT_IMAGES[vendor.category] || CATEGORY_DEFAULT_IMAGES[vendor.category?.toLowerCase()] || CATEGORY_DEFAULT_IMAGES['Venue'];

  const hasValidImage = vendor.image && vendor.image.trim() !== '' && !vendor.image.includes('pexels.com');
  const mainImage = hasValidImage ? vendor.image : categoryDefault.main;

  const validGallery = (vendor.gallery || []).filter(img => img && img.trim() !== '' && !img.includes('pexels.com'));
  const gallery = validGallery.length > 0 ? validGallery : [mainImage, ...categoryDefault.gallery];

  return { image: mainImage, gallery };
}

